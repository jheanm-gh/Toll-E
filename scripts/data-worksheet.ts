/**
 * Generate the verification worksheet: every current tariff and journey sequence that still
 * needs a human check, grouped by the official document to check it against.
 *   npm run data:worksheet   → docs/verification/worksheet.md
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { STANDARD_CLASSES, formatZAR, resolveStandardTariff, buildTariffIndex } from '../packages/core/src/index.ts';
import { ROOT, loadDataset, publishedSubset, today } from './lib/data.ts';

const ds = publishedSubset(loadDataset().dataset);
const date = today();
const index = buildTariffIndex(ds);
const sources = new Map(ds.sources.map((s) => [s.id, s]));

/** Which official document each operator's tariffs must be checked against. */
const OFFICIAL: Record<string, { sourceId: string; how: string }> = {
  sanral: {
    sourceId: 'sanral-tariffs-2026-poster',
    how: 'SANRAL 2026 tariff poster; if anything is unclear, the Government Gazette Nos. 54087/54088 of 5 February 2026 is authoritative.',
  },
  n3tc: {
    sourceId: 'sanral-tariffs-2026-poster',
    how: 'The SANRAL 2026 poster lists the N3TC plazas. Also open the N3TC tariff page and note which figures it shows; the Gazette resolves any disagreement.',
  },
  trac: { sourceId: 'trac-toll-fees', how: 'TRAC "Toll plazas & toll fees" page (2026 table).' },
  bakwena: {
    sourceId: 'bakwena-tolls-and-tariffs',
    how: 'Bakwena "Tolls and Tariffs" page (valid 1 March 2026 – 28 February 2027).',
  },
  'chapmans-peak': { sourceId: 'chapmans-peak-gazette-2026', how: 'Provincial Notice 138/2026, Schedule A.' },
};

const lines: string[] = [
  '# Verification worksheet',
  '',
  `_Generated by \`npm run data:worksheet\` for ${date}. Do not edit by hand — regenerate after verifying._`,
  '',
  'How to use: open the official document named in each section, compare every row, tick it, and write the',
  'correct amount next to any row that differs. Then record the result with `npm run data:verify` (commands are',
  'given per section). See [README.md](./README.md).',
  '',
];

const operators = [...new Set(ds.plazas.map((p) => p.operatorId))];
for (const opId of operators) {
  const op = ds.operators.find((o) => o.id === opId);
  const official = OFFICIAL[opId];
  const doc = official ? sources.get(official.sourceId) : undefined;
  const rows: string[] = [];
  const schedules = new Set<string>();
  for (const p of ds.plazas.filter((x) => x.operatorId === opId)) {
    for (const c of STANDARD_CLASSES) {
      const r = resolveStandardTariff(index, p.id, c, { date });
      if (r.kind === 'none' && r.reason === 'class_not_supported') continue;
      if (r.kind === 'current') {
        schedules.add(r.tariff.scheduleId);
        if (r.tariff.verificationStatus === 'verified') continue;
        rows.push(
          `| [ ] | ${p.name} (${p.route}) | ${c.replace('class', '')} | ${formatZAR(r.tariff.amountCents)} | ${r.tariff.verificationStatus.replace('_', ' ')} | ${r.tariff.sourceId} | \`${r.tariff.id}\` |`,
        );
      } else {
        rows.push(
          `| [ ] | ${p.name} (${p.route}) | ${c.replace('class', '')} | **missing** | — | — | add a row to the schedule CSV |`,
        );
      }
    }
  }
  if (!rows.length) continue;
  lines.push(`## ${op?.name ?? opId}`, '');
  if (doc && official) {
    lines.push(`Check against: **[${doc.title}](${doc.url})** — ${official.how}`, '');
    lines.push('Record (after checking every row):', '', '```');
    for (const s of schedules) {
      lines.push(
        `npm run data:verify -- --by "Your Full Name" --against ${official.sourceId} --schedule ${s} [--except <ids that differ>] [--correct <id>=<amount>]`,
      );
    }
    lines.push('```', '');
  }
  lines.push(
    '| ✓ | Plaza | Class | Toll-E value | Status | Current source | Tariff id |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
  );
}

lines.push(
  '## Journey plaza sequences',
  '',
  'For each route, confirm from an operator or SANRAL route description (or by driving it) that the',
  'listed plazas are all the mainline plazas you pass, in this order.',
  '',
);
for (const j of ds.journeys.filter((x) => x.sequenceStatus !== 'verified')) {
  const names = j.events.map((e) => {
    const n = ds.plazas.find((p) => p.id === e.plazaId)?.name ?? e.plazaId;
    return e.requirement === 'conditional' ? `(${n} — conditional)` : n;
  });
  lines.push(
    `- [ ] **${j.name} (${j.via})**: ${names.join(' → ')}  `,
    `  \`npm run data:verify -- --by "Your Full Name" --journey ${j.id}\``,
  );
}
lines.push('');

const dir = join(ROOT, 'docs/verification');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'worksheet.md'), lines.join('\n'));
console.log(`wrote docs/verification/worksheet.md (${lines.length} lines)`);
