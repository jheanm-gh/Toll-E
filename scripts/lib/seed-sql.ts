import type { Dataset } from '../../packages/core/src/index.ts';

type SqlValue = string | number | boolean | null | undefined | SqlRaw;
class SqlRaw {
  constructor(readonly sql: string) {}
}
const raw = (sql: string) => new SqlRaw(sql);

function lit(v: SqlValue): string {
  if (v === null || v === undefined) return 'null';
  if (v instanceof SqlRaw) return v.sql;
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`non-finite number in seed: ${v}`);
    return String(v);
  }
  return `'${v.replace(/'/g, "''")}'`;
}

function arr(values: readonly string[] | undefined, type = 'text'): SqlRaw {
  if (!values || values.length === 0) return raw(`'{}'::${type}[]`);
  return raw(`array[${values.map(lit).join(', ')}]::${type}[]`);
}

function insert(table: string, columns: string[], rows: SqlValue[][]): string {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const body = rows.map((r) => `  (${r.map(lit).join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${body};\n`;
}

/** Generate supabase/seed.sql from the canonical dataset (all publication states). */
export function datasetToSeedSql(ds: Dataset): string {
  const parts: string[] = [
    '-- GENERATED by `npm run data:build` from data/. Do not edit by hand.',
    `-- Dataset version ${ds.datasetVersion}. Loads into a freshly migrated database.`,
    'begin;',
    "set local tolle.seeding = 'on';",
    '',
  ];

  parts.push(
    insert(
      'sources',
      ['id', 'title', 'publisher', 'url', 'kind', 'official', 'published_on', 'retrieved_on', 'reference', 'notes'],
      ds.sources.map((s) => [
        s.id,
        s.title,
        s.publisher,
        s.url,
        s.kind,
        s.official,
        s.publishedOn,
        s.retrievedOn,
        s.reference,
        s.notes,
      ]),
    ),
  );
  parts.push(
    insert(
      'operators',
      [
        'id',
        'name',
        'short_name',
        'kind',
        'website',
        'phone',
        'email',
        'contact_status',
        'payment_methods',
        'payment_status',
        'payment_source_ids',
        'payment_notes',
        'source_ids',
        'notes',
      ],
      ds.operators.map((o) => [
        o.id,
        o.name,
        o.shortName,
        o.kind,
        o.website,
        o.phone,
        o.email,
        o.contactStatus,
        o.payment ? arr(o.payment.methods) : null,
        o.payment?.status,
        arr(o.payment?.sourceIds),
        o.payment?.notes,
        arr(o.sourceIds),
        o.notes,
      ]),
    ),
  );
  parts.push(
    insert(
      'toll_roads',
      ['id', 'name', 'routes', 'operator_id', 'provinces', 'description', 'source_ids'],
      ds.tollRoads.map((r) => [
        r.id,
        r.name,
        arr(r.routes),
        r.operatorId,
        arr(r.provinces, 'public.province_code'),
        r.description,
        arr(r.sourceIds),
      ]),
    ),
  );
  parts.push(
    insert(
      'vehicle_class_schemes',
      ['id', 'name', 'from_standard', 'source_ids'],
      ds.vehicleClassSchemes.map((s) => [
        s.id,
        s.name,
        raw(`${lit(JSON.stringify(s.fromStandard))}::jsonb`),
        arr(s.sourceIds),
      ]),
    ),
  );
  parts.push(
    insert(
      'vehicle_classes',
      ['scheme_id', 'id', 'label', 'short_description', 'description', 'sort_order'],
      ds.vehicleClassSchemes.flatMap((s) =>
        s.classes.map((c, i) => [s.id, c.id, c.label, c.shortDescription, c.description, i + 1]),
      ),
    ),
  );
  parts.push(
    insert(
      'plazas',
      [
        'id',
        'name',
        'toll_road_id',
        'operator_id',
        'route',
        'type',
        'province',
        'locality',
        'carriageway',
        'lat',
        'lng',
        'location_precision',
        'location_source_ids',
        'location_notes',
        'status',
        'class_scheme_id',
        'source_ids',
        'aliases',
        'notes',
        'publication_status',
      ],
      ds.plazas.map((p) => [
        p.id,
        p.name,
        p.tollRoadId,
        p.operatorId,
        p.route,
        p.type,
        p.province,
        p.locality,
        p.carriageway,
        p.location?.lat,
        p.location?.lng,
        p.location?.precision,
        arr(p.location?.sourceIds),
        p.location?.notes,
        p.status,
        p.classSchemeId,
        arr(p.sourceIds),
        arr(p.aliases),
        arr(p.notes),
        p.publicationStatus,
      ]),
    ),
  );
  parts.push(
    insert(
      'tariff_schedules',
      [
        'id',
        'name',
        'operator_ids',
        'effective_from',
        'effective_to',
        'next_review_expected',
        'adjustment_bps',
        'source_ids',
        'notes',
      ],
      ds.schedules.map((s) => [
        s.id,
        s.name,
        arr(s.operatorIds),
        s.effectiveFrom,
        s.effectiveTo,
        s.nextReviewExpected,
        s.adjustmentBps,
        arr(s.sourceIds),
        s.notes,
      ]),
    ),
  );
  const plazaScheme = new Map(ds.plazas.map((p) => [p.id, p.classSchemeId]));
  parts.push(
    insert(
      'tariffs',
      [
        'id',
        'plaza_id',
        'vehicle_class_id',
        'class_scheme_id',
        'amount_cents',
        'currency',
        'vat_inclusive',
        'charging_basis',
        'direction',
        'condition',
        'effective_from',
        'effective_to',
        'schedule_id',
        'source_id',
        'source_locator',
        'checked_on',
        'verified_on',
        'verified_by',
        'verification_status',
        'publication_status',
        'notes',
      ],
      ds.tariffs.map((t) => [
        t.id,
        t.plazaId,
        t.vehicleClassId,
        plazaScheme.get(t.plazaId),
        t.amountCents,
        t.currency,
        t.vatInclusive,
        t.chargingBasis,
        t.direction,
        t.condition,
        t.effectiveFrom,
        t.effectiveTo,
        t.scheduleId,
        t.sourceId,
        t.sourceLocator,
        t.checkedOn,
        t.verifiedOn,
        t.verifiedBy,
        t.verificationStatus,
        t.publicationStatus,
        t.notes,
      ]),
    ),
  );
  parts.push(
    insert(
      'journeys',
      [
        'id',
        'name',
        'origin_label',
        'origin_query',
        'destination_label',
        'destination_query',
        'via',
        'description',
        'sequence_status',
        'sequence_verified_on',
        'sequence_verified_by',
        'limitations',
        'source_ids',
        'publication_status',
      ],
      ds.journeys.map((j) => [
        j.id,
        j.name,
        j.origin.label,
        j.origin.query,
        j.destination.label,
        j.destination.query,
        j.via,
        j.description,
        j.sequenceStatus,
        j.sequenceVerifiedOn,
        j.sequenceVerifiedBy,
        arr(j.limitations),
        arr(j.sourceIds),
        j.publicationStatus,
      ]),
    ),
  );
  parts.push(
    insert(
      'journey_events',
      ['journey_id', 'leg', 'seq', 'plaza_id', 'direction', 'requirement', 'condition'],
      ds.journeys.flatMap((j) => [
        ...j.events.map((e, i) => [j.id, 'outbound', i + 1, e.plazaId, e.direction, e.requirement, e.condition]),
        ...(j.returnEvents ?? []).map((e, i) => [
          j.id,
          'return',
          i + 1,
          e.plazaId,
          e.direction,
          e.requirement,
          e.condition,
        ]),
      ]),
    ),
  );
  parts.push(
    insert(
      'notices',
      ['id', 'title', 'body', 'severity', 'show_from', 'show_until', 'source_ids'],
      ds.notices.map((n) => [n.id, n.title, n.body, n.severity, n.showFrom, n.showUntil, arr(n.sourceIds)]),
    ),
  );
  parts.push(
    `insert into public.dataset_meta (key, value) values ('dataset_version', ${lit(ds.datasetVersion)})\n` +
      '  on conflict (key) do update set value = excluded.value;\n',
  );
  parts.push('commit;\n');
  return parts.join('\n');
}
