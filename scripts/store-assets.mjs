// Render Google Play listing assets into docs/store/ from the app's web build.
//   npm run build:web && npx serve -s apps/mobile/dist -l 8081 &
//   node scripts/store-assets.mjs
// Screenshots are 1080×1920 (9:16). They come from the web build, which runs the same screens
// as the Android app; replace them with device captures before the production release if
// anything differs (see docs/release/play-store-listing.md).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs/store');
const base = process.env.BASE_URL ?? 'http://localhost:8081';
mkdirSync(join(out, 'screenshots'), { recursive: true });

const browser = await chromium.launch({
  args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
});

// Feature graphic 1024×500.
{
  const icon = readFileSync(join(root, 'apps/mobile/assets/images/icon.png')).toString('base64');
  const html = readFileSync(join(out, 'feature-graphic.html'), 'utf8').replace('ICON_B64', icon);
  const page = await (await browser.newContext({ viewport: { width: 1024, height: 500 } })).newPage();
  await page.setContent(html, { waitUntil: 'load' });
  await page.screenshot({ path: join(out, 'feature-graphic.png') });
  console.log('feature-graphic.png');
}

// Hi-res icon 512×512.
{
  const icon = readFileSync(join(root, 'apps/mobile/assets/images/icon.png')).toString('base64');
  const page = await (await browser.newContext({ viewport: { width: 512, height: 512 } })).newPage();
  await page.setContent(
    `<html><body style="margin:0"><img src="data:image/png;base64,${icon}" style="width:512px;height:512px;display:block"></body></html>`,
  );
  await page.screenshot({ path: join(out, 'icon-512.png') });
  console.log('icon-512.png');
}

// Phone screenshots: [file, path, text to scroll into view (optional), clicks before capture]
const shots = [
  ['1-home', '/', null, []],
  ['2-plaza', '/plazas/n4-machado', null, []],
  ['3-tariffs', '/plazas/n4-machado', 'Tariffs by vehicle class', []],
  ['4-calculator', '/calculate?journey=jhb-dbn-n3', 'Plaza sequence not yet checked', []],
  ['5-result', '/calculate?journey=jhb-dbn-n3', 'Estimated toll cost', []],
  ['6-map', '/map', null, []],
  ['7-directory', '/plazas', null, []],
];
const ctx = await browser.newContext({ viewport: { width: 360, height: 640 }, deviceScaleFactor: 3 });
const page = await ctx.newPage();
for (const [name, path, scrollTo] of shots) {
  await page.goto(base + path, { waitUntil: 'networkidle' }).catch(() => {});
  await page.waitForTimeout(2500);
  if (scrollTo) {
    const target = page.getByText(scrollTo, { exact: false }).first();
    await target.evaluate((el) => el.scrollIntoView({ block: 'start' })).catch(() => {});
    // Leave a little space above the target.
    await page.evaluate(() => {
      const scroller = [...document.querySelectorAll('div')].find(
        (d) => d.scrollHeight > d.clientHeight + 10 && getComputedStyle(d).overflowY !== 'visible',
      );
      scroller?.scrollBy(0, -24);
    });
    await page.evaluate(() => new Promise((r) => setTimeout(r, 400)));
  }
  await page.screenshot({ path: join(out, 'screenshots', `${name}.png`) });
  console.log(`screenshots/${name}.png`);
}
await browser.close();
writeFileSync(
  join(out, 'screenshots', 'README.md'),
  '# Screenshots\n\nGenerated by `node scripts/store-assets.mjs` from the web build (1080×1920).\n',
);
