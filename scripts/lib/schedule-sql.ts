import type { Dataset } from '../../packages/core/src/index.ts';

const q = (v: string | number | boolean | null | undefined): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};
const arr = (xs: readonly string[] | undefined, type = 'text') =>
  xs && xs.length ? `array[${xs.map(q).join(', ')}]::${type}[]` : `'{}'::${type}[]`;

/**
 * SQL for loading one tariff schedule into Supabase from the SQL editor. Safe to run more than
 * once: sources and plazas are added if missing, the schedule is upserted, and tariffs are
 * inserted as DRAFTS (existing drafts are updated; published rows are never touched).
 * Publishing is a separate, deliberate step: select public.publish_schedule(...).
 */
export function scheduleUpdateSql(ds: Dataset, scheduleId: string): string {
  const schedule = ds.schedules.find((s) => s.id === scheduleId);
  if (!schedule) throw new Error(`unknown schedule ${scheduleId}`);
  const tariffs = ds.tariffs.filter((t) => t.scheduleId === scheduleId && t.publicationStatus !== 'withdrawn');
  if (!tariffs.length) throw new Error(`schedule ${scheduleId} has no tariffs`);
  const plazaIds = new Set(tariffs.map((t) => t.plazaId));
  const sourceIds = new Set([...schedule.sourceIds, ...tariffs.map((t) => t.sourceId)]);
  const plazas = ds.plazas.filter((p) => plazaIds.has(p.id));
  for (const p of plazas) p.sourceIds.forEach((s) => sourceIds.add(s));
  const out: string[] = [
    `-- Toll-E tariff update: ${schedule.name} (${scheduleId})`,
    `-- Generated by npm run data:supabase-sql. Paste into Supabase → SQL editor and run.`,
    `-- Loads ${tariffs.length} tariffs as DRAFTS. Nothing is visible in the app until you publish.`,
    'begin;',
    '',
  ];
  for (const s of ds.sources.filter((x) => sourceIds.has(x.id))) {
    out.push(
      `insert into public.sources (id, title, publisher, url, kind, official, published_on, retrieved_on, reference, notes) values (${[
        s.id,
        s.title,
        s.publisher,
        s.url,
        s.kind,
        s.official,
        s.publishedOn,
        s.retrievedOn,
        s.reference,
        s.notes,
      ]
        .map(q)
        .join(
          ', ',
        )})\n  on conflict (id) do update set title = excluded.title, url = excluded.url, retrieved_on = excluded.retrieved_on, reference = excluded.reference, notes = excluded.notes;`,
    );
  }
  for (const p of plazas) {
    out.push(
      `insert into public.plazas (id, name, toll_road_id, operator_id, route, type, province, locality, lat, lng, location_precision, location_source_ids, location_notes, class_scheme_id, source_ids, aliases, notes, publication_status) values (${[
        q(p.id),
        q(p.name),
        q(p.tollRoadId),
        q(p.operatorId),
        q(p.route),
        q(p.type),
        q(p.province),
        q(p.locality),
        q(p.location?.lat),
        q(p.location?.lng),
        q(p.location?.precision),
        arr(p.location?.sourceIds),
        q(p.location?.notes),
        q(p.classSchemeId),
        arr(p.sourceIds),
        arr(p.aliases),
        arr(p.notes),
        q(p.publicationStatus),
      ].join(', ')})\n  on conflict (id) do nothing;`,
    );
  }
  out.push(
    `insert into public.tariff_schedules (id, name, operator_ids, effective_from, effective_to, next_review_expected, adjustment_bps, source_ids, notes) values (${[
      q(schedule.id),
      q(schedule.name),
      arr(schedule.operatorIds),
      q(schedule.effectiveFrom),
      q(schedule.effectiveTo),
      q(schedule.nextReviewExpected),
      q(schedule.adjustmentBps),
      arr(schedule.sourceIds),
      q(schedule.notes),
    ].join(
      ', ',
    )})\n  on conflict (id) do update set name = excluded.name, effective_to = excluded.effective_to, next_review_expected = excluded.next_review_expected, adjustment_bps = excluded.adjustment_bps, source_ids = excluded.source_ids, notes = excluded.notes;`,
    '',
  );
  const schemeOf = new Map(ds.plazas.map((p) => [p.id, p.classSchemeId]));
  for (const t of tariffs) {
    out.push(
      `insert into public.tariffs (id, plaza_id, vehicle_class_id, class_scheme_id, amount_cents, direction, condition, effective_from, effective_to, schedule_id, source_id, source_locator, checked_on, verified_on, verified_by, verification_status, publication_status, notes) values (${[
        t.id,
        t.plazaId,
        t.vehicleClassId,
        schemeOf.get(t.plazaId),
        t.amountCents,
        t.direction,
        t.condition,
        t.effectiveFrom,
        t.effectiveTo,
        t.scheduleId,
        t.sourceId,
        t.sourceLocator,
        t.checkedOn,
        t.verifiedOn,
        t.verifiedBy,
        t.verificationStatus,
        'draft',
        t.notes,
      ]
        .map(q)
        .join(
          ', ',
        )})\n  on conflict (id) do update set amount_cents = excluded.amount_cents, source_id = excluded.source_id, source_locator = excluded.source_locator, checked_on = excluded.checked_on, verified_on = excluded.verified_on, verified_by = excluded.verified_by, verification_status = excluded.verification_status, notes = excluded.notes where public.tariffs.publication_status = 'draft';`,
    );
  }
  out.push(
    '',
    'commit;',
    '',
    `-- Review every change before publishing (compare new and previous amounts):`,
    `select plaza_name, vehicle_class_id, previous_amount_cents / 100.0 as previous_rand, new_amount_cents / 100.0 as new_rand, change_percent, verification_status`,
    `from public.schedule_review where schedule_id = ${q(scheduleId)} and publication_status = 'draft' order by plaza_name, vehicle_class_id;`,
    '',
    `-- When you are satisfied, publish (replace the name with yours):`,
    `-- select public.publish_schedule(${q(scheduleId)}, 'Your Full Name');`,
    '',
  );
  return out.join('\n');
}
