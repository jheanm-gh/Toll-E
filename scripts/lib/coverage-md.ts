import {
  PROVINCE_NAMES,
  STANDARD_CLASSES,
  TRUST_LABEL,
  computeCoverage,
  formatLongDate,
  formatZAR,
  releaseReadiness,
  summariseCoverage,
  type CoverageFlag,
  type Dataset,
} from '../../packages/core/src/index.ts';

/** A check of the data against sources, recorded in data/verification-log.json. */
export interface VerificationCheck {
  date: string;
  by: string;
  scope: string;
  attempted: string;
  outcome: string;
  result: string;
}

const FLAG: Record<CoverageFlag, string> = {
  yes: '✅ verified',
  partial: '◐ partial',
  unverified: '⚠ unverified',
  no: '✖ none',
};

export function renderCoverageMarkdown(dataset: Dataset, today: string, checks: VerificationCheck[] = []): string {
  const rows = computeCoverage(dataset, today);
  const release = releaseReadiness(dataset, today);
  const s = summariseCoverage(dataset, today);
  const operators = new Map(dataset.operators.map((o) => [o.id, o.shortName]));
  const lines: string[] = [
    '# Toll-E data coverage register',
    '',
    `_Generated by \`npm run data:build\` from \`data/\` (dataset ${dataset.datasetVersion}), evaluated for ${formatLongDate(today)}. Do not edit by hand._`,
    '',
    'This register says plainly what Toll-E knows and does not know. "Verified" means a person has checked the',
    'record against an official source; nothing in the seed dataset has reached that state yet.',
    '',
    '## Summary',
    '',
    `| Measure | Count |`,
    `|---|---|`,
    `| Toll plazas listed | ${s.plazas} |`,
    `| …with an approximate map position | ${s.withLocation - s.withVerifiedLocation} |`,
    `| …with a verified map position | ${s.withVerifiedLocation} |`,
    `| …with at least one current tariff | ${s.withAnyCurrentTariff} |`,
    `| …with current tariffs for every vehicle class | ${s.withCompleteClassCoverage} |`,
    `| …with verified current tariffs | ${s.withVerifiedCurrentTariff} |`,
    ...Object.entries(s.tariffsByStatus).map(([k, v]) => `| Published tariff records: ${k} | ${v} |`),
    '',
    '## Coverage by corridor and vehicle class',
    '',
    'One-way totals for the tariffs in force on the evaluation date. Each cell shows the total, how many of the',
    "route's chargeable plazas have a price, and the weakest status among them. A corridor can only be offered in a",
    'production build once its plaza sequence is verified (`offeredJourneys`).',
    '',
    `| Corridor | Plaza sequence | ${STANDARD_CLASSES.map((c) => `Class ${c.slice(-1)}`).join(' | ')} |`,
    `|---|---|${STANDARD_CLASSES.map(() => '---').join('|')}|`,
    ...release.corridors.map(
      (c) =>
        `| ${c.name} (${c.via}) | ${c.sequenceVerified ? '✅ verified' : '⚠ unverified'} | ${STANDARD_CLASSES.map(
          (cls) => {
            const x = c.byClass[cls];
            if (x.priced === 0) return '✖ no price';
            const trust = x.trust ? TRUST_LABEL[x.trust].toLowerCase() : 'unknown';
            return `${formatZAR(x.totalCents)} · ${x.priced}/${x.chargeable} · ${trust}`;
          },
        ).join(' | ')} |`,
    ),
    '',
    `Release gate (\`npm run release:check\`): **${release.ready ? 'ready' : 'not ready'}** — ${release.verifiedSlots} of ${release.plazaClassSlots} plaza-class prices verified; ${release.gaps.length} gaps.`,
    '',
    '## Verification checks',
    '',
    'Recorded in `data/verification-log.json`. Individual verified tariffs also carry `verified_on` and `verified_by`.',
    '',
    ...(checks.length === 0
      ? ['No checks recorded.']
      : [
          '| Date | By | Scope | What was attempted | Outcome | Result |',
          '|---|---|---|---|---|---|',
          ...checks.map((k) => `| ${k.date} | ${k.by} | ${k.scope} | ${k.attempted} | ${k.outcome} | ${k.result} |`),
        ]),
    '',
    '## Per plaza',
    '',
    'Columns: **Location** (verified position?), **Operator** (contact details verified?), **Current tariff**',
    '(verified and in force?), **Classes** (vehicle classes with a current tariff), **Charging rules** (plaza type and',
    'charging conditions verified?), **Payment** (payment methods verified?).',
    '',
    '| Plaza | Route | Operator | Province | Location | Operator info | Current tariff | Classes | Charging rules | Payment |',
    '|---|---|---|---|---|---|---|---|---|---|',
  ];
  const sorted = [...rows].sort(
    (a, b) =>
      a.plaza.route.localeCompare(b.plaza.route, 'en', { numeric: true }) || a.plaza.name.localeCompare(b.plaza.name),
  );
  for (const r of sorted) {
    const p = r.plaza;
    const tariffCell =
      r.currentTariff === 'no' ? FLAG.no : r.tariffTrust === 'under_review' ? '⚠ under review' : FLAG[r.currentTariff];
    lines.push(
      `| ${p.name} (${p.type}) | ${p.route} | ${operators.get(p.operatorId) ?? p.operatorId} | ${p.province ? PROVINCE_NAMES[p.province] : '—'} | ${FLAG[r.location]} | ${FLAG[r.operator]} | ${tariffCell} | ${r.classCoverage.available}/${r.classCoverage.total} | ${FLAG[r.chargingRules]} | ${FLAG[r.payment]} |`,
    );
  }
  lines.push(
    '',
    '## Known gaps',
    '',
    '- No position, operator detail, tariff or payment method has been verified by a person yet.',
    "- N3TC tariffs are under review: the operator website (as indexed) and SANRAL's 2026 poster disagree.",
    '- Several ramp plazas and the N17 plazas east of Dalpark have no tariff loaded because only one third-party source was found.',
    '- Frequent-user, local-user and e-tag discounts are not modelled.',
    '- R30/R730/R34 toll roads (Free State) listed in older SANRAL gazettes are not yet researched.',
    '',
  );
  return lines.join('\n');
}
